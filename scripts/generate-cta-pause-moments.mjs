// Generate `src/demo/content/<id>/ads/cta-pause.json` from the Tier 3 product
// source.
//
//   DHYH (default):
//     node scripts/generate-cta-pause-moments.mjs
//
//   Any other content tile (e.g. MasterChef with two custom windows):
//     node scripts/generate-cta-pause-moments.mjs \
//       --content masterchef \
//       --windows 30-75,135-195
//
// CTA Pause shows the pause-to-shop CTA only inside fixed editorial WINDOWS
// that MUST mirror the content's `*_CTA_PAUSE_WINDOWS` constant in its
// `timeline.ts`. Pausing inside a window reveals the time-accurate top-5
// products; pausing outside does nothing. This script tiles each window with
// scene-accurate moments (the same trailing-5 rolling logic the Products panel
// + Organic Pause use) so any pause within a window resolves to the right
// products.
//
// The campaign THEME block (pause-to-shop CTA art, sponsor logos, detail-screen
// art) is PRESERVED verbatim from the existing cta-pause.json — those are
// designer/client-supplied assets, independent of the product data. For a fresh
// content tile, seed `ads/cta-pause.json` with `{"campaign":[{...empty theme...}]}`
// before running this script.
//
// Knobs (see scripts/lib/pause-moments-core.mjs for full docs):
//   TIME_BASE    — 'clip' (clip-native timestamps, any length) | 'source-splice'
//   IMAGE_SOURCE — { mode: 'cdn' | 'local' | 's3', s3Base? }  (local↔CDN↔S3 swap)

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  collectCandidates,
  dedupeProducts,
  trailingProducts,
  buildSceneEntry,
  buildDocument,
} from './lib/pause-moments-core.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

// ── CLI args ───────────────────────────────────────────────────────────────
// --content <id>     (default: 'dhyh')
// --windows a-b,c-d  (default: DHYH-historical [77,107] + [153,532])
const args = process.argv.slice(2)
const argValue = (name) => {
  const i = args.indexOf(name)
  return i >= 0 ? args[i + 1] : null
}
const CONTENT_ID = argValue('--content') ?? 'dhyh'
const WINDOWS_ARG = argValue('--windows')

const TIER3_PATH = join(ROOT, `src/demo/content/${CONTENT_ID}/tiers/tier3.json`)
const CTA_PATH = join(ROOT, `src/demo/content/${CONTENT_ID}/ads/cta-pause.json`)

// ── Knobs ──────────────────────────────────────────────────────────────────
const TIME_BASE = 'clip'
const IMAGE_SOURCE = { mode: 'cdn', s3Base: 'https://REPLACE-ME.s3.amazonaws.com/products' }
const DEDUPE_WINDOW_SECONDS = 90
const MAX_PRODUCTS_PER_MOMENT = 5

// Editorial CTA windows (clip-time seconds). MUST mirror the per-content
// `*_CTA_PAUSE_WINDOWS` constant in the corresponding timeline.ts. Default
// is the historical DHYH pair (short + long).
const DEFAULT_DHYH_WINDOWS = [
  [77, 107],
  [153, 532],
]
const CTA_PAUSE_WINDOWS = WINDOWS_ARG
  ? WINDOWS_ARG.split(',').map((pair) => {
      const [a, b] = pair.split('-').map(Number)
      if (!Number.isFinite(a) || !Number.isFinite(b) || b <= a) {
        throw new Error(
          `--windows entry "${pair}" is malformed; expected "<startSec>-<endSec>" with end > start.`
        )
      }
      return [a, b]
    })
  : DEFAULT_DHYH_WINDOWS

const tier3 = JSON.parse(readFileSync(TIER3_PATH, 'utf8'))
const existing = JSON.parse(readFileSync(CTA_PATH, 'utf8'))
const theme = existing.campaign?.[0] ?? {}

const candidates = collectCandidates(tier3, TIME_BASE)
const deduped = dedupeProducts(candidates, DEDUPE_WINDOW_SECONDS)

// Most-recent candidate scene number at or before a clip-time (for the `scene` label).
const sceneNumberAt = (t) => {
  let sn = candidates[0]?.sceneNumber ?? 0
  for (const c of candidates) {
    if (c.clipStart <= t + 0.001) sn = c.sceneNumber
    else break
  }
  return sn
}

// For each CTA window, tile [wStart, wEnd] with moments: a moment starts at the
// window start and at every product-scene boundary inside the window, each
// ending at the next boundary (or the window end). This guarantees any pause
// inside the window lands on a moment with the time-accurate trailing-5.
const scenes = []
for (const [wStart, wEnd] of CTA_PAUSE_WINDOWS) {
  const inner = candidates
    .map((c) => c.clipStart)
    .filter((t) => t > wStart && t < wEnd)
  const boundaries = [wStart, ...inner].sort((a, b) => a - b)
  for (let i = 0; i < boundaries.length; i++) {
    const start = boundaries[i]
    const end = i + 1 < boundaries.length ? boundaries[i + 1] : wEnd
    if (end <= start) continue
    const products = trailingProducts(deduped, start, MAX_PRODUCTS_PER_MOMENT)
    scenes.push(buildSceneEntry(sceneNumberAt(start), start, end, products, IMAGE_SOURCE))
  }
}

const output = buildDocument({
  videoId: existing.video_id ?? 'DB-DemoVid1',
  note:
    'Auto-generated by `scripts/generate-cta-pause-moments.mjs` from `tier3.json`. ' +
    'Do not edit by hand — re-run the script when Tier 3 changes. The editorial ' +
    'CTA windows (when the pause-to-shop hint is visible during playback, and when ' +
    'pausing surfaces the carousel) are emitted as `cta_pause_windows` at the top ' +
    'level — that is the source of truth the app reads from. Each entry in ' +
    '`campaign[].scenes` is a moment inside one of those windows; the trailing-5 ' +
    'products at that clip-time. The theme block is preserved from the prior file ' +
    '(designer/client-supplied CTA + sponsor assets). ' +
    `Image source: ${IMAGE_SOURCE.mode}.`,
  campaignId: theme.campaign_id ?? `${CONTENT_ID}-cta-pause`,
  theme,
  scenes,
  ctaPauseWindows: CTA_PAUSE_WINDOWS,
})

writeFileSync(CTA_PATH, JSON.stringify(output, null, 2) + '\n', 'utf8')
console.log(
  `Wrote ${CTA_PATH}\n  windows: ${CTA_PAUSE_WINDOWS.length}\n  moments: ${scenes.length}\n  total product tiles: ${scenes.reduce((n, s) => n + s.objects.length, 0)}`
)
