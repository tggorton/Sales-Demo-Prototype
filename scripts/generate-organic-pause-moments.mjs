// Generate `src/demo/content/<id>/ads/organic-pause.json` from the Tier 3
// product source.
//
//   DHYH (default):
//     node scripts/generate-organic-pause-moments.mjs
//
//   Any other content tile (e.g. MasterChef):
//     node scripts/generate-organic-pause-moments.mjs --content masterchef
//
// Organic Pause lets the user pause at ANY point and see the time-accurate
// top-5 products (no editorial windows — the CTA hint only shows in the first
// few seconds of playback, gated separately in the app). This script emits one
// moment per product-scene, each window running until the next product-scene,
// populated with the trailing-5 rolling product list.
//
// The campaign THEME block is shared with CTA Pause (reused verbatim from
// `ads/cta-pause.json`) so both modes use the same designer/client CTA + sponsor
// assets. **Run the CTA generator FIRST so the shared theme is present.**
//
// Knobs (see scripts/lib/pause-moments-core.mjs for full docs):
//   TIME_BASE    — 'clip' (clip-native timestamps, any length) | 'source-splice'
//   IMAGE_SOURCE — { mode: 'cdn' | 'local' | 's3', s3Base? }  (local↔CDN↔S3 swap)

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  collectCandidates,
  dedupeProducts,
  trailingProducts,
  buildSceneEntry,
  buildDocument,
} from './lib/pause-moments-core.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

// ── CLI args ───────────────────────────────────────────────────────────────
// --content <id>  (default: 'dhyh')
const args = process.argv.slice(2)
const argValue = (name) => {
  const i = args.indexOf(name)
  return i >= 0 ? args[i + 1] : null
}
const CONTENT_ID = argValue('--content') ?? 'dhyh'

const TIER3_PATH = join(ROOT, `src/demo/content/${CONTENT_ID}/tiers/tier3.json`)
const CTA_PATH = join(ROOT, `src/demo/content/${CONTENT_ID}/ads/cta-pause.json`)
const OUT_PATH = join(ROOT, `src/demo/content/${CONTENT_ID}/ads/organic-pause.json`)

// ── Knobs ──────────────────────────────────────────────────────────────────
const TIME_BASE = 'clip'
const IMAGE_SOURCE = { mode: 'cdn', s3Base: 'https://REPLACE-ME.s3.amazonaws.com/products' }
const DEDUPE_WINDOW_SECONDS = 90
const MAX_PRODUCTS_PER_MOMENT = 5

const tier3 = JSON.parse(readFileSync(TIER3_PATH, 'utf8'))
const ctaDoc = JSON.parse(readFileSync(CTA_PATH, 'utf8'))
const theme = ctaDoc.campaign?.[0] ?? {}

// Clip length comes from the source payload, so this is length-agnostic.
const clipDuration = Number(tier3.duration_in_seconds) || 0

const candidates = collectCandidates(tier3, TIME_BASE)
const deduped = dedupeProducts(candidates, DEDUPE_WINDOW_SECONDS)

const scenes = candidates.map((c, i) => {
  // The first moment starts at clip-time 0 (not the first product-scene's
  // start) so Organic Pause — "pause at ANY time" — has coverage from the very
  // beginning; an early pause shows the first scene's products.
  const start = i === 0 ? 0 : c.clipStart
  const end = candidates[i + 1] ? candidates[i + 1].clipStart : clipDuration
  const products = trailingProducts(deduped, c.clipStart, MAX_PRODUCTS_PER_MOMENT)
  return buildSceneEntry(c.sceneNumber, start, end, products, IMAGE_SOURCE)
})

const output = buildDocument({
  videoId: ctaDoc.video_id ?? 'DB-DemoVid1',
  note:
    'Auto-generated by `scripts/generate-organic-pause-moments.mjs` from `tier3.json`. ' +
    'Do not edit by hand — re-run the script when Tier 3 changes. One moment per ' +
    'product-scene; each shows the trailing-5 products at that clip-time. Theme block ' +
    'is reused verbatim from `ads/cta-pause.json` so both pause modes share campaign ' +
    `assets. Image source: ${IMAGE_SOURCE.mode}.`,
  campaignId: `${CONTENT_ID}-organic-pause`,
  theme,
  scenes,
})

writeFileSync(OUT_PATH, JSON.stringify(output, null, 2) + '\n', 'utf8')
console.log(
  `Wrote ${OUT_PATH}\n  moments: ${scenes.length}\n  total product tiles: ${scenes.reduce((n, s) => n + s.objects.length, 0)}`
)
